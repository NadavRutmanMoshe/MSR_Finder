def tab_msreh():
    import lasso_size as LS          # smallest-lasso size of an explanation
    ah, hq, eh = (load("MSR/msr_autohyper.csv"), load("MSR/msr_hyperqb.csv"),
                  load("MSR/explainhyper.csv"))

    # SIZE IS TRACE LENGTH, NOT AN EVENT COUNT.  The column used to sum the
    # finite and per-loop pins, i.e. the number of events the tool PRINTS --
    # but a starred pin denotes infinitely many events on the trace, so that
    # number is not comparable with $|C|$ and is not what the appendix's
    # Table~\ref{tab:data-resultsizes} reports.  Both columns are now the
    # length of the trace prefix the explanation fixes, the one measure that
    # means the same thing on both sides.
    def best(n):
        """(seconds, which backend) for the backend that found an MSR fastest.
        2026-10-14 (Hadar: the bottom line must equal Table tab:sumall): only
        SAT_MSR counts here. AutoHyper's SAT_SR (proof that no MSR exists) is
        an answer for tab_main, but its reason is not minimal, so it is not
        compared with a minimal cause; same rule as bench_figs.tab_resultsizes."""
        cap = 300.0 + 10.0 if hq[n]["inputs"] == "4" else WALL_CAP   # |IP|=4: 300 s
        cand = [(num(r["wall_s"]), tag)
                for r, tag in ((ah[n], "AH"), (hq[n], "HQ"))
                if is_answer(r) and r["status"] == "SAT_MSR"
                and num(r["wall_s"]) is not None and num(r["wall_s"]) <= cap]
        return min(cand) if cand else (None, None)

    lines, tot_eh, tot_ours, no_msr = [], 0, 0, 0
    tot_win = collections.Counter()
    # |IP|=4 row (marked *, 300 s) when the view holds the ip4 instances
    has4 = any(hq[n]["inputs"] == "4" for n in hq)
    for ip in ("1", "2", "3") + (("4",) if has4 else ()) + (None,):
        sel = [n for n in hq if ip is None or hq[n]["inputs"] == ip]
        ours = [n for n in sel if best(n)[0] is not None]
        eha = [n for n in sel if eh[n]["status"] == "OK"]
        both = sorted(set(ours) & set(eha))
        wins = collections.Counter(best(n)[1] for n in both)
        # Six columns, not ten. The earlier version set "answered by EH",
        # "answered by us" and "answered by both" side by side under one rule,
        # and a reader could not tell which of the three the means were over.
        # Only the intersection can carry a comparison, so that is the count in
        # the table; the other two go in the caption, where they explain
        # instead of competing for the eye.
        label = "all" if ip is None else ip
        if has4 and ip in ("4", None):
            label += r"$^{*}$"
        row = [label, len(both),
               mean([num(eh[n]["wall_s"]) for n in both]),
               mean([best(n)[0] for n in both]),
               # size = smallest lasso of the explanation (Nadav, 2026-10-14)
               mean([LS.sizes(n, ah[n] if best(n)[1] == "AH" else hq[n])[1]
                     for n in both], "{:.1f}"),
               mean([LS.sizes(n, ah[n] if best(n)[1] == "AH" else hq[n])[0]
                     for n in both], "{:.1f}")]
        if ip is None:                # the `all` pass already spans the family;
            tot_eh = len(eha)                         # accumulating the three
            tot_ours = sum(1 for n in sel if answered(ah[n]) or answered(hq[n]))
            no_msr = sum(1 for n in sel if eh[n]["status"] == "OK"
                         and best(n)[0] is None and answered(ah[n]))
            tot_win = wins                # |ip| rows as well would double it
        lines.append(" & ".join(str(c) for c in row) + r" \\")
        if ip == ("4" if has4 else "3"):
            lines.append(r"\midrule")

    body = "\n".join([
        r"\toprule",
        r"& & \multicolumn{2}{c}{avg.\ $t$ (s)} & \multicolumn{2}{c}{avg.\ size} \\",
        r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}",
        r"$|\ip|$ & instances & tool in \cite{coenen2022hyperproperty} & $\MSR$ & $|C|$ & $|R|$ \\",  # Overleaf zip (12), Hadar, 2026-10-15
        r"\midrule", *lines, r"\bottomrule"])
    return wrap(
        body,
        # caption shortened with Nadav, 2026-10-14
        r"$\MSR$ against \cite{coenen2022hyperproperty}, on the instances where both return "  # Overleaf zip (12), Hadar, 2026-10-15
        r"an explanation (" + str(no_msr) + r" instances on which no $\MSR$ exists are "
        r"excluded). The size of an explanation is the size $|u|+|v|$ of the "
        r"smallest lasso $u v^\omega$ that describes it. \cite{coenen2022hyperproperty} "
        r"returns several minimal causes, and we take the smallest."
        + (r" $^{*}$\,Timeout of 300\,s instead of 120\,s." if has4 else "") +
        # Hadar's comment, verbatim from Overleaf zip (10), 2026-10-14
        r"\hadar{add results for ip size 4}",
        "msreh", r"r@{\hspace{10pt}}r@{\hspace{12pt}}r@{\hspace{12pt}}r@{\hspace{12pt}}rr")


