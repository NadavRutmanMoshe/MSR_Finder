def tab_main():
    """Sec. 6's headline table.  With $IP4_RESULTS set (results_catsrl/ip4),
    the |IP|=4 instances are a fourth row, marked * because they had 300 s
    instead of 120 s (Nadav/Hadar, 2026-10-14: Tables 1 and 2 merged), and
    the `all' row covers both.  Only |IP|=4 instances on which every tool has
    finished are counted, so a partial run gives a partial row (the paper
    carries a \todo while that is the case)."""
    ah, hq, mt = (load("MSR/msr_autohyper.csv"), load("MSR/msr_hyperqb.csv"),
                  load("MTSR_CORP/mtsr.csv"))
    cap = {n: WALL_CAP for n in hq}
    ip4dir = os.environ.get("IP4_RESULTS")
    n4 = 0
    if ip4dir:
        def l4(rel):
            return _read(os.path.join(ip4dir, rel))
        ah4, hq4, mt4 = (l4("MSR/msr_autohyper.csv"), l4("MSR/msr_hyperqb.csv"),
                         l4("MTSR_CORP/mtsr.csv"))
        done = [n for n in hq4 if n in ah4 and n in mt4]
        n4 = len(done)
        for n in done:
            ah[n], hq[n], mt[n], cap[n] = ah4[n], hq4[n], mt4[n], 300.0 + 10.0

    def ok(r, n):
        w = num(r["wall_s"])
        return is_answer(r) and w is not None and w <= cap[n]

    def best(n):
        c = [num(r["wall_s"]) for r in (ah[n], hq[n]) if ok(r, n)]
        return min(c) if c else None

    star = r"$^{*}$"
    lines = []
    for ip in ("1", "2", "3") + (("4",) if n4 else ()) + (None,):
        sel = [n for n in hq if ip is None or hq[n]["inputs"] == ip]
        if not sel:                  # a re-run subset without this |IP|
            continue
        solved = [n for n in sel if best(n) is not None]
        mo = [n for n in sel if n in mt and mt[n]["mtsr_status"] == "OK"]
        label = "all" if ip is None else ip
        if n4 and ip in ("4", None):
            label += star
        lines.append(" & ".join(str(x) for x in [
            label, len(sel),
            f"{100 * len(solved) // len(sel)}\\,\\%",
            mean([best(n) for n in solved]),
            f"{100 * len(mo) // len(sel)}\\,\\%",
            mean([num(mt[n]["mtsr_s"]) for n in mo]),
            mean([num(mt[n]["mtsr_states"]) for n in mo], "{:.1f}"),
        ]) + r" \\")
        if ip == ("4" if n4 else "3"):
            lines.append(r"\midrule")
    body = "\n".join([
        r"\toprule",
        r"& & \multicolumn{2}{c}{$\MSR$} & \multicolumn{3}{c}{$\MTSR$} \\",
        r"\cmidrule(lr){3-4}\cmidrule(lr){5-7}",
        r"$|\ip|$ & instances & solved & avg.\ $t$ (s) & solved & avg.\ $t$ (s) & avg.\ $|A|$ \\",
        r"\midrule", *lines, r"\bottomrule"])
    # caption shortened with Nadav, 2026-10-14 (`solved' is defined in Sec. 6.1)
    tail = r" $^{*}$\,Timeout of 300\,s instead of 120\,s." if n4 else ""
    return wrap(
        body,
        r"Results of \tool\ on the \num{" + str(len(hq)) + r"} instances. For $\MSR$ "
        r"(solved as in \S\ref{sec:bench}), the time is that of the faster model "
        r"checker; $|A|$ is the number of states of the $\MTSR$ automaton. "
        r"Averages are over the solved instances." + tail +
        # Overleaf zip (12), Hadar, 2026-10-15 (replaces her zip (9) comment)
        r"\hadar{this timeout comment needs to be rephrased. also, add more space between the columns}",
        "main", r"r@{\hspace{10pt}}r@{\hspace{10pt}}rr@{\hspace{10pt}}rrr",
        placement="t")


def tab_effclass():
    """Where a minimal reason fails to exist -- by the shape of the effect.

    BUCKETED BY HOW THE EFFECT WAS GENERATED, not by its leading operator.
    Matching `^G F` against the formula text put every randltl draw that
    happens to start with F or G into a template row: the F row read 162 when
    only 120 of those are templates, and the 11 "sufficient" results in the G
    row were all random effects, which is why that row claimed 19% where the
    real G template row is 0%. effect_source/effect_shape come from the
    generator itself (bench/scripts/effect_gen.py), via bench_stats_extra.py.
    """
    ah = load("MSR/msr_autohyper.csv")
    ex = load_stats("extra.csv")

    order = [("F", r"$\LTLeventually\ell$"), ("G", r"$\LTLglobally\ell$"),
             ("GF", r"$\LTLglobally\LTLeventually\ell$"),
             ("FG", r"$\LTLeventually\LTLglobally\ell$"),
             (None, "random")]
    lines = []
    for key, sh in order:
        if key is None:
            sel = [n for n in ah
                   if ex.get(n, {}).get("effect_source") == "randltl"]
        else:
            sel = [n for n in ah
                   if ex.get(n, {}).get("effect_source") == "template"
                   and ex[n]["effect_shape"] == key]
        if not sel:
            continue
        m = sum(1 for n in sel if ah[n]["status"] == "SAT_MSR")
        r_ = sum(1 for n in sel if ah[n]["status"] == "SAT_SR")
        lines.append(" & ".join(str(x) for x in [
            sh, len(sel), m, r_, len(sel) - m - r_,
            f"{100 * r_ // (m + r_) if m + r_ else 0}\\,\\%"]) + r" \\")
        if key == "FG":
            lines.append(r"\midrule")
    body = "\n".join([
        r"\toprule",
        r"& & \multicolumn{3}{c}{$\MSR$ outcome} & \\",
        r"\cmidrule(lr){3-5}",
        r"effect shape & instances & minimal & sufficient & none & "
        r"\% sufficient \\",
        r"\midrule", *lines, r"\bottomrule"])
    return wrap(
        body,
        r"$\MSR$ outcomes by the temporal shape of the effect, over the "
        r"\num{409} templated instances; the \num{409} \texttt{randltl} "
        r"effects are the last row. Rows follow the generator, not the leading "
        r"operator of the formula. For safety and reachability a minimal reason "
        r"is found whenever the instance is solved at all; under the liveness "
        r"shapes the \texttt{SAT\_SR} fallback dominates, which is "
        r"\Cref{thm:nomsr} in the data --- causes shrink indefinitely, so no "
        r"minimal reason exists and the only correct answer is a non-minimal "
        r"one.",
        "effclass", r"l@{\hspace{12pt}}r@{\hspace{12pt}}rrr@{\hspace{12pt}}r")


