#: The budget is 120s per SOLVER QUERY (every *_bench.py defaults to
#: --timeout 120). Building the model handed to the solver is outside that
#: budget, so total wall clock can exceed it on an instance that was answered
#: within budget: 182 answers land in [120,130)s. Ten seconds of slack keeps
#: those -- discarding them would drop 45 genuine answers and read as a
#: capability limit -- and rejects the 11 that overshot for real, 5 of them by
#: more than an hour (all abcg_arbiter3). Same rule as bench_figs.WALL_CAP, so
#: \S7 and the appendix count the same answers.
WALL_CAP = 130.0


def load(rel):
    p = os.path.join(RESULTS, rel)
    if not os.path.exists(p):
        sys.exit(f"missing {p} -- run bench/paper/make_tables.py, which builds the view")
    return _read(p)


def load_stats(rel):
    """A CSV from claude_scripts/results/bench_stats/ -- derived data that
    bench_stats_extra.py computed from the benchmark, not raw benchmark
    output, so it lives in this repo rather than in demo_tool."""
    p = os.path.join(paths.STATS, rel)
    if not os.path.exists(p):
        sys.exit(f"missing {p} -- run bench/paper/make_tables.py first")
    return _read(p)


def _read(p):
    with open(p, newline="") as f:
        rows = list(csv.DictReader(f))
    key = "instance" if rows and "instance" in rows[0] else "name"
    return {os.path.splitext(r[key])[0]: r for r in rows}


def answered(row):
    """Answered, and inside the wall-clock rule above."""
    w = num(row["wall_s"])
    return is_answer(row) and w is not None and w <= WALL_CAP


def reason_span(row):
    """Trace length of our reason: steps 0..last pinned step. A pin in the loop
    (`@t*`) recurs forever but sits at one lasso position, so the loop counts
    once -- the lasso is the finite form of the infinite trace. The same
    measure bench_figs.reason_span reports in Table~\\ref{tab:data-resultsizes},
    so the two tables no longer size the same reason two different ways."""
    ps = [int(x.split("@")[1].rstrip("*"))
          for x in (row.get("reason") or "").split(",") if x]
    return max(ps) + 1 if ps else None


def cause_span(row):
    """Trace length of ExplainHyper's shortest cause: steps 0..its last event."""
    try:
        return min(max(e[1] for e in c) + 1
                   for c in ast.literal_eval(row["causes"]))
    except Exception:
        return None


def num(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def med(vals, spec="{:.2f}"):
    """Median, for the columns \S7.2 reports that way -- a solved-instance
    time distribution has a tail against the 120s cap, and a mean there
    describes the cap rather than the tool."""
    vals = [v for v in vals if v is not None]
    return spec.format(st.median(vals)) if vals else "--"


def mean(vals, spec="{:.2f}"):
    vals = [v for v in vals if v is not None]
    return spec.format(st.mean(vals)) if vals else "--"


def wrap(body, caption, label, colspec, placement="htbp"):
    return (f"\\begin{{table}}[{placement}]\n\\centering\n\\caption{{{caption}}}\n"
            f"\\label{{tab:{label}}}\n"
            f"\\begin{{tabular}}{{@{{}}{colspec}@{{}}}}\n{body}\n"
            f"\\end{{tabular}}\n\\end{{table}}\n")


