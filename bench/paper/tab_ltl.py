#!/usr/bin/env python3
"""Table data-ltl: is the MTSR automaton expressible by a small LTL formula?

Reads results/stats/mtsr_ltl.csv and mtsr_ltl_meta.json, written by
ltl_rerun_catsrl.py (the search over all formulas up to a size bound, run on
the 915 instances of both corpora whose MTSR was computed; 913 automata, two
autfilt timeouts). bench_figs.tab_ltl predates the |IP| = 4 corpus, so the
|IP| = 4 row of the submitted table was filled in by hand from this CSV; this
writes the same table from the data.

    python3 tab_ltl.py            -> PAPER_OUT/tables/tab_data_ltl.tex
"""
import csv
import json
import os
import statistics as st
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import paths  # noqa: E402


def hd(*lines):
    return r"\begin{tabular}[b]{@{}c@{}}" + r"\\".join(lines) + r"\end{tabular}"


def main():
    rows = list(csv.DictReader(open(os.path.join(paths.STATS, "mtsr_ltl.csv"))))
    reached = json.load(open(os.path.join(paths.STATS, "mtsr_ltl_meta.json")))["reached"]
    body = []
    for k in ("1", "2", "3", "4", None):
        sel = [r for r in rows if k is None or r["k"] == k]
        found = [r for r in sel if r["ltl_size"]]
        if k is None:
            body.append(r"\midrule")
        avg = lambda c: "{:.1f}".format(st.mean(float(r[c]) for r in found)) if found else "--"
        body.append(" & ".join(str(x) for x in [
            "all" if k is None else k, len(sel), len(found), len(sel) - len(found),
            avg("ltl_size"), avg("states")]) + r" \\")
    tex = "\n".join([
        "% generated by bench/paper/tab_ltl.py -- do not edit",
        r"\begin{table}[htbp]", r"\centering", r"\footnotesize",
        r"\renewcommand{\arraystretch}{1.3}",
        r"\begin{tabular}{@{}rr@{\hspace{14pt}}r@{\hspace{12pt}}r@{\hspace{14pt}}r@{\hspace{12pt}}r@{}}",
        r"\toprule",
        r"& & \multicolumn{2}{c}{found} & & \\",
        r"\cmidrule(lr){3-4}",
        r"$|\ip|$ & automata & yes & no & " + hd("avg.", "formula size") + " & "
        + hd("avg.", "automaton size") + r" \\",
        r"\midrule", *body, r"\bottomrule", r"\end{tabular}", r"\vspace{6pt}",
        r"\caption{The smallest LTL formula equivalent to the $\MTSR$ automaton, searched "
        r"up to size %s (%s for $|\ip| = 3$, %s for $|\ip| = 4$). `yes' / `no': whether one "
        r"was found; the averages are over the automata for which one was found.}"
        % (reached["1"], reached["3"], reached["4"]),
        r"\label{tab:data-ltl}", r"\end{table}", ""])
    out = os.path.join(paths.TABLES, "tab_data_ltl.tex")
    open(out, "w").write(tex)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
