#!/usr/bin/env python3
"""Appendix D (Hadar, 2026-10-16): MSR with AutoHyper against HyperQB.

  * Table tab:msr-backends -- times only, on the instances that BOTH model
    checkers solve, rows |IP| = 1..4 and all (style of tab_main, Table 1).
  * Figure fig:data-msr-backends-time -- one point per instance, x = AutoHyper
    time, y = HyperQB time, in the style of fig_cats_check_time (Fig. 7):
    an instance a model checker did not solve within the timeout is a cross at
    n/a on that axis (both: the corner).

Same data and rules as paper_tables.tab_main: BENCH_RESULTS=results/view_catsrl,
IP4_RESULTS=.../results_catsrl/ip4 (|IP|=4 rows, 300 s); solved = is_answer()
within the wall cap (HyperQB SAT_SR never counts). Writes
tacas2027_2/tables/tab_msr_backends.tex, figures/fig_data_msr_backends_time.tex
and figures/data_msr_backends_time.pdf (or --print for the table only)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import paper_tables as P

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

FIGS = P.paths.FIGURES
# style of bench_figs.py (Fig. 7)
BLUE, INK, MUTED, GRID = "#2a78d6", "#0b0b0b", "#52514e", "#e4e3df"
TW = 4.8
ALPHA, SIZE = 0.35, 7
plt.rcParams.update({
    "font.family": "serif", "mathtext.fontset": "cm", "font.size": 7.5,
    "axes.edgecolor": MUTED, "axes.labelcolor": INK, "axes.linewidth": 0.6,
    "xtick.color": MUTED, "ytick.color": MUTED, "xtick.major.width": 0.5,
    "ytick.major.width": 0.5, "axes.grid": True, "grid.color": GRID,
    "grid.linewidth": 0.5, "axes.axisbelow": True, "legend.frameon": False,
    "legend.fontsize": 6.5, "axes.spines.top": False, "axes.spines.right": False,
    "pdf.fonttype": 42,
})


def data():
    ah, hq = P.load("MSR/msr_autohyper.csv"), P.load("MSR/msr_hyperqb.csv")
    cap = {n: P.WALL_CAP for n in hq}
    ip4dir = os.environ.get("IP4_RESULTS")
    n4 = 0
    if ip4dir:
        ah4 = P._read(os.path.join(ip4dir, "MSR/msr_autohyper.csv"))
        hq4 = P._read(os.path.join(ip4dir, "MSR/msr_hyperqb.csv"))
        mt4 = P._read(os.path.join(ip4dir, "MTSR_CORP/mtsr.csv"))
        done = [n for n in hq4 if n in ah4 and n in mt4]   # as tab_main
        n4 = len(done)
        for n in done:
            ah[n], hq[n], cap[n] = ah4[n], hq4[n], 300.0 + 10.0

    def t(r, n):
        w = P.num(r["wall_s"])
        return w if P.is_answer(r) and w is not None and w <= cap[n] else None

    ta = {n: t(ah[n], n) for n in hq}
    th = {n: t(hq[n], n) for n in hq}
    ips = {n: hq[n]["inputs"] for n in hq}
    return ta, th, ips, n4


def table(ta, th, ips, n4):
    lines = []
    for ip in ("1", "2", "3") + (("4",) if n4 else ()) + (None,):
        sel = [n for n in ta if ip is None or ips[n] == ip]
        a = [n for n in sel if ta[n] is not None]
        h = [n for n in sel if th[n] is not None]
        both = [n for n in a if th[n] is not None]
        label = "all" if ip is None else ip
        if n4 and ip in ("4", None):
            label += r"$^{*}$"
        row = [label, len(sel), len(a), len(h), len(both),
               P.mean([ta[n] for n in both]), P.mean([th[n] for n in both])]
        lines.append(" & ".join(str(c) for c in row) + r" \\")
        if ip == ("4" if n4 else "3"):
            lines.append(r"\midrule")
    body = "\n".join([
        r"\toprule",
        r"& & \multicolumn{3}{c}{solved} & \multicolumn{2}{c}{avg.\ $t$ (s), solved by both} \\",
        r"\cmidrule(lr){3-5}\cmidrule(lr){6-7}",
        r"$|\ip|$ & instances & \textsc{AutoHyper} & \textsc{HyperQB} & both"
        r" & \textsc{AutoHyper} & \textsc{HyperQB} \\",
        r"\midrule", *lines, r"\bottomrule"])
    tail = r" $^{*}$\,For $|\ip| = 4$, the timeout was 300\,s (120\,s for the other rows)." if n4 else ""
    cap_txt = (r"$\MSR$ with \textsc{AutoHyper} and with \textsc{HyperQB} on the "
               r"instances of \Cref{tab:main}: the number of instances that each model "
               r"checker solves (as in \Cref{sec:bench}), and the average running time "
               r"on the instances that both solve." + tail)
    return ("% generated by bench/paper/tab_msr_backends.py -- do not edit\n"
            "\\begin{table}[t]\n\\centering\n"
            "\\begin{tabular}{@{}r@{\\hspace{10pt}}r@{\\hspace{14pt}}r@{\\hspace{8pt}}r"
            "@{\\hspace{8pt}}r@{\\hspace{14pt}}r@{\\hspace{8pt}}r@{}}\n"
            + body + "\n\\end{tabular}\n\\vspace{6pt}\n"
            "\\caption{" + cap_txt + "}\n\\label{tab:msr-backends}\n\\end{table}\n")


def figure(ta, th, ips, n4):
    names = sorted(ta)
    sel = [n for n in names if ta[n] is not None and th[n] is not None]
    miss = [n for n in names if n not in sel]
    xs, ys = [ta[n] for n in sel], [th[n] for n in sel]
    fig, ax = plt.subplots(figsize=(TW * 0.55, 2.3))
    ax.scatter(xs, ys, s=SIZE, color=BLUE, alpha=ALPHA, linewidths=0)
    ax.set_xscale("log"); ax.set_yscale("log")
    lo = min(0.1, min(xs + ys) * 0.8)
    hi = max(xs + ys) * 1.3
    na = hi * 2.2                                   # the "no answer" band
    mx = [na if ta[n] is None else ta[n] for n in miss]
    my = [na if th[n] is None else th[n] for n in miss]
    ax.scatter(mx, my, s=14, marker="x", color=BLUE, alpha=ALPHA, linewidths=0.8, zorder=3)
    ax.axhline(hi * 1.5, color="0.6", lw=0.4, ls=":"); ax.axvline(hi * 1.5, color="0.6", lw=0.4, ls=":")
    ax.set_xlim(lo, na * 1.6); ax.set_ylim(lo, na * 1.6)
    ax.plot([lo, hi], [lo, hi], color=MUTED, lw=0.6, ls=(0, (3, 2)), zorder=0)
    ticks = [t for t in (0.01, 0.1, 1, 10, 100) if lo <= t <= hi] + [na]
    labels = [r"$10^{%d}$" % round(__import__("math").log10(t)) for t in ticks[:-1]] + ["n/a"]
    for axis in (ax.xaxis, ax.yaxis):
        axis.set_ticks(ticks); axis.set_ticklabels(labels); axis.set_minor_locator(plt.NullLocator())
    ax.set_xlabel("AutoHyper time (s)")
    ax.set_ylabel("HyperQB time (s)")
    ax.set_aspect("equal")
    fig.savefig(os.path.join(FIGS, "data_msr_backends_time.pdf"), bbox_inches="tight", pad_inches=0.02)
    plt.close(fig)
    only_a = sum(1 for n in miss if ta[n] is not None)
    only_h = sum(1 for n in miss if th[n] is not None)
    none = sum(1 for n in miss if ta[n] is None and th[n] is None)
    faster = sum(1 for x, y in zip(xs, ys) if x < y)
    tail = r" (300\,s for $|\ip| = 4$)" if n4 else ""
    caption = (r"$\MSR$ with \textsc{AutoHyper} against \textsc{HyperQB} on the "
               + str(len(names)) + r" instances, one point per instance. Above the "
               r"diagonal, \textsc{AutoHyper} is faster. Crosses (n/a): the model "
               r"checker did not solve the instance within 120\,s" + tail + ".")
    with open(os.path.join(FIGS, "fig_data_msr_backends_time.tex"), "w") as fh:
        fh.write("% generated by bench/paper/tab_msr_backends.py -- do not edit\n"
                 "\\begin{figure}[t]\n\\centering\n"
                 "\\includegraphics[width=0.55\\textwidth]{figures/data_msr_backends_time.pdf}\n"
                 "\\caption{" + caption + "}\n\\label{fig:data-msr-backends-time}\n"
                 "\\end{figure}\n")
    return dict(both=len(sel), ah_faster=faster, only_ah=only_a, only_hq=only_h, none=none)


if __name__ == "__main__":
    d = data()
    tab = table(*d)
    if "--print" in sys.argv:
        print(tab)
        sys.exit()
    p = os.path.join(P.TABLES, "tab_msr_backends.tex")
    open(p, "w").write(tab)
    print("wrote", p)
    print("figure:", figure(*d))
