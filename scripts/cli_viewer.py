#!/usr/bin/env python3
"""
The Presentation/UI layer: color-coded terminal tables for the MSR results.

Coloring is per-variable: the input propositions pinned by the cause (true in
Tau) are shown in green — in both the Tau and the Pi column — rather than
highlighting whole rows.
"""
import sys
import textwrap

import trace_analyzer

GREEN = "\033[92m"
RESET = "\033[0m"


def format_reason_set(tau_prefix, tau_cycle, allowed):
    """Render Tau as an explicit set of (variable, timestep) pairs.

    Prefix steps carry literal timesteps. Loop steps repeat forever, so step k
    of the loop occurs at |prefix| + k + i*|loop| for every i >= 0 — writing
    that out states the infinite cause exactly, instead of leaving it implicit
    behind the omega in the lasso notation.

        Tau = {r0}{} ({r0}{})^w    ->    {(r0,0),(r0,2+i*2) | i in N u {0}}
    """
    n_prefix, n_loop = len(tau_prefix), len(tau_cycle)
    allowed = set(allowed)

    terms = []
    for t, step in enumerate(tau_prefix):
        terms += [f"({v},{t})" for v in sorted(step & allowed)]

    loop_terms = []
    for k, step in enumerate(tau_cycle):
        pinned = sorted(step & allowed)
        if not pinned:
            continue
        rep = "i" if n_loop == 1 else f"i*{n_loop}"
        base = n_prefix + k
        idx = rep if base == 0 else f"{base}+{rep}"
        loop_terms += [f"({v},{idx})" for v in pinned]

    terms += loop_terms
    if not terms:
        return "{}   (the empty cause — nothing needs to be pinned)"
    tail = " | i ∈ ℕ ∪ {0} }" if loop_terms else " }"
    return "{ " + ", ".join(terms) + tail


def _print_block(label, value, width=92, indent=4, trailing_blank=False):
    """Label on its own line, value wrapped and indented beneath it.

    PI/Tau lasso strings and the Reason R set are all unbounded in length, so
    putting them on the same line as a label made the block ragged and forced
    the terminal to wrap mid-token. Wrapping happens on the separators the
    values already contain (the space before a lasso's loop, and ", " between
    set terms), so breaks land in meaningful places.
    """
    print(f"{label}:")
    for line in textwrap.wrap(value, width=width - indent,
                              break_long_words=False, break_on_hyphens=False,
                              initial_indent=" " * indent,
                              subsequent_indent=" " * indent) or [" " * indent]:
        print(line)
    if trailing_blank:
        print()


def print_cli_results(result_data, pi_override=None, show_pi=True):
    """
    Takes the raw dictionary generated by the backend and formats it into
    human-readable terminal tables, coloring the pinned inputs green.

    `show_pi=False` suppresses the PI line entirely.

    `pi_override` prints that string instead of `result_data['pi_string']`.
    Callers that synthesized the trace themselves (pi_finder) use this: the PI
    the MSR pipeline reports back is projected onto the INPUTS and re-unrolled,
    whereas the trace they found is over the real system and carries its
    outputs, so it is the one worth showing.
    """
    print(f"Effect: {result_data['effect']}")
    status = result_data["status"]

    # --- ERROR & EDGE CASE HANDLING ---
    if status == "NON_DETERMINISTIC":
        print(f"\n{'='*80}")
        print(" \033[95m[!] STATUS: AMBIGUOUS SYSTEM (Non-Deterministic)\033[0m")
        print(f"{'='*80}")
        print(" Causality requires an input-deterministic system. Your system allows")
        print(" multiple different outcomes for the exact same input state.")
        print(f"\n DETAILS: {result_data.get('error_msg')}")
        print(f"{'='*80}\n")
        return

    if status == "ERROR":
        print(f"\n{'='*80}")
        print(" \033[91m[!] EXECUTION FAILED\033[0m")
        print(f"{'='*80}")
        print(result_data.get('error_msg', 'Unknown Error'))
        print(f"{'='*80}\n")
        return

    if status == "INVALID_PI":
        print(f"\n{'='*80}")
        print(" \033[91mSTATUS: INVALID TRACE (Pi is not a valid path or does not satisfy the effect!)\033[0m")
        print(f"{'='*80}")
        print(" AutoHyper proved that the trace provided in the [lasso] block is either:")
        print("   - not a physically possible path within the system's HOA graph, or")
        print("   - a valid path on which the [effect] formula does not actually occur.")
        print(" -> Aborting causality check.")
        print(f"{'='*80}\n")
        return

    if status == "UNSAT_NO_CAUSE":
        print(f"\n{'='*80}")
        print(" \033[93mSTATUS: UNSAT (Valid Trace, but No Cause Exists)\033[0m")
        print(f"{'='*80}")
        print(" The Pi trace is valid, but AutoHyper proved that no sufficient")
        print(" cause exists for this system configuration.")
        print(f"{'='*80}\n")
        return

    # --- SUCCESS HANDLING ---
    if status == "SAT_MSR":
        print("\n\033[92mStatus: SAT (Minimal Sufficient Reason Found)\033[0m\n")
    elif status == "SAT_SR":
        print("\n\033[93mStatus: SAT (No Minimal Cause found, but found a Sufficient Reason)\033[0m\n")
        # Not a solver failure: when no MSR exists, every sufficient reason is
        # infinite and each one strictly contains a smaller sufficient reason,
        # so there is no smallest one to report. Typical for liveness effects
        # (G F / F G), where a cause can be pushed further into the future
        # forever.
        print("\033[2m  Why: no MSR exists for this instance -- the sufficient reasons form an\033[0m")
        print("\033[2m  infinite descending chain R0 > R1 > R2 > ..., so none is minimal.\033[0m")
        print("\033[2m  The reason below is sufficient but not minimal.\033[0m\n")

    if show_pi:
        # "found" only when we synthesized the trace ourselves; in option 1 the
        # PI came from the user's [lasso] block. strip() because an empty lasso
        # prefix renders as a leading space.
        _label = "found PI" if pi_override else "PI"
        _print_block(_label, (pi_override or result_data["pi_string"]).strip(),
                     trailing_blank=True)
    _print_block("found reason representation Tau",
                 result_data["tau_string"].strip(), trailing_blank=True)
    _td = result_data.get("table_data") or {}
    _print_block("Reason R",
                 format_reason_set(_td.get("tau_prefix", []),
                                   _td.get("tau_cycle", []),
                                   result_data["cause_vars"] or []))

    # --- DYNAMIC TABLE FORMATTING ---
    vars_to_show = result_data["cause_vars"]
    if not vars_to_show:
        vars_to_show = ["(No specific cause vars detected)"]

    col_width = max(len('REASON REPRESENTATION (Tau)'), len(vars_to_show) * 8)

    print(f"\n{'=' * (col_width * 2 + 25)}")
    print(f"{'TIME':<5} | {'REASON REPRESENTATION (Tau)':<{col_width}} | {'ACTUAL TRACE (Pi)':<{col_width}} | {'STATUS'}")
    print(f"{'=' * (col_width * 2 + 25)}")

    def fmt(v_set, green_vars):
        """
        Format a set of active variables into a 'name=T/F' string.
        Any variable in `green_vars` (the inputs pinned by Tau) is wrapped in
        green.  Returns (colored_string, visible_length) so callers can pad
        correctly despite the invisible ANSI escape codes.
        """
        parts = []
        visible_len = 0
        for i, v in enumerate(vars_to_show):
            if v == "(No specific cause vars detected)":
                return "", 0
            val = "T" if v in v_set else "F"
            token = f"{v}={val}"
            sep = "" if i == 0 else ", "
            visible_len += len(sep) + len(token)
            if v in green_vars:
                parts.append(f"{sep}{GREEN}{token}{RESET}")
            else:
                parts.append(f"{sep}{token}")
        return "".join(parts), visible_len

    def pad(cell, visible_len):
        """Pad a (possibly colored) cell to col_width using its visible length."""
        return cell + " " * max(0, col_width - visible_len)

    def print_row(t, tau_vars, pi_vars):
        """Print one timestep row with per-variable green highlighting."""
        # The inputs that are TRUE in Tau drive the coloring in BOTH columns.
        green_vars = {v for v in vars_to_show if v in tau_vars}
        is_cause = len(green_vars) > 0
        marker = f"{GREEN}<-- REASON DETECTED{RESET}" if is_cause else ""

        tau_cell, tau_len = fmt(tau_vars, green_vars)
        pi_cell,  pi_len  = fmt(pi_vars,  green_vars)

        print(f"{t:<5} | {pad(tau_cell, tau_len)} | {pad(pi_cell, pi_len)} | {marker}")

    # --- PREFIX PRINTING ---
    td = result_data["table_data"]
    pi_p, pi_c = td["pi_prefix"], td["pi_cycle"]
    tau_p, tau_c = td["tau_prefix"], td["tau_cycle"]

    max_prefix = max(len(pi_p), len(tau_p))
    for i in range(max_prefix):
        p_step = pi_p[i] if i < len(pi_p) else set()
        t_step = tau_p[i] if i < len(tau_p) else set()
        print_row(i, t_step, p_step)

    # --- CYCLE PRINTING ---
    print(f"{'-'*5} + {'-'*col_width} + {'-'*col_width} + {'-'*15}")
    print(f"{'CYCLE':<5} | {'(Repeating Pattern)':<{col_width}} | {'(Repeating Pattern)':<{col_width}} |")
    print(f"{'-'*5} + {'-'*col_width} + {'-'*col_width} + {'-'*15}")

    max_cycle = max(len(pi_c), len(tau_c))
    current_time_idx = max_prefix
    for i in range(max_cycle):
        p_step = pi_c[i] if i < len(pi_c) else set()
        t_step = tau_c[i] if i < len(tau_c) else set()
        print_row(current_time_idx, t_step, p_step)
        current_time_idx += 1

    print(f"{'=' * (col_width * 2 + 25)}\n")


def main():
    if len(sys.argv) < 2:
        print("Usage: python3 cli_viewer.py <input.txt>")
        sys.exit(1)
    results = trace_analyzer.analyze_trace(sys.argv[1])
    print_cli_results(results)


if __name__ == "__main__":
    main()
