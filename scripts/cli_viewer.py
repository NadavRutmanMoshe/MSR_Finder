#!/usr/bin/env python3
"""
The Presentation/UI layer: color-coded terminal tables for the MSR results.

Coloring is per-variable: the input propositions pinned by the cause (true in
Tau) are shown in green, rather than highlighting whole rows.

The table is COMPACT by default — one trace column, the actual trace Pi, with
the pinned positions green:

    TIME  | ACTUAL TRACE (Pi) | REASON (R)

Tau is not shown, because it says nothing the green spots do not: `"ip"_tau` is
the *indicator* of membership in R (the formula pins pi via
`{"ip"_tau} -> ({"ip"_pi} <-> {"ip"_pi2})`), not a valuation of the trace. Its
T/F cells ARE the green cells, and printing them beside Pi's real values
invited reading a green `r1=T` in the Tau column as "r1 is true here" even when
Pi has `r1=F` at that pinned position. Now that R is reported explicitly as a
set, the column is pure noise.

`show_tau=True` restores the previous two-column layout (Tau next to Pi) plus
the `found reason representation Tau` block, for anyone who wants to see the
witness the cause was read off.
"""
import sys
import textwrap

import trace_analyzer

GREEN = "\033[92m"
RESET = "\033[0m"


def format_reason_set(tau_prefix, tau_cycle, allowed):
    """Render Tau as an explicit set of (variable, timestep) pairs.

    Prefix steps carry literal timesteps. Loop steps repeat forever, so step k
    of the loop occurs at |prefix| + k + i*|loop| for every i >= 0 — writing
    that out states the infinite cause exactly, instead of leaving it implicit
    behind the omega in the lasso notation.

        Tau = {r0}{} ({r0}{})^w    ->    {(r0,0),(r0,2+i*2) | i in N u {0}}
    """
    n_prefix, n_loop = len(tau_prefix), len(tau_cycle)
    allowed = set(allowed)

    terms = []
    for t, step in enumerate(tau_prefix):
        terms += [f"({v},{t})" for v in sorted(step & allowed)]

    loop_terms = []
    for k, step in enumerate(tau_cycle):
        pinned = sorted(step & allowed)
        if not pinned:
            continue
        rep = "i" if n_loop == 1 else f"i*{n_loop}"
        base = n_prefix + k
        idx = rep if base == 0 else f"{base}+{rep}"
        loop_terms += [f"({v},{idx})" for v in pinned]

    terms += loop_terms
    if not terms:
        return "{}   (the empty cause — nothing needs to be pinned)"
    tail = " | i ∈ ℕ ∪ {0} }" if loop_terms else " }"
    return "{ " + ", ".join(terms) + tail


def _print_block(label, value, width=92, indent=4, trailing_blank=False):
    """Label on its own line, value wrapped and indented beneath it.

    PI/Tau lasso strings and the Reason R set are all unbounded in length, so
    putting them on the same line as a label made the block ragged and forced
    the terminal to wrap mid-token. Wrapping happens on the separators the
    values already contain (the space before a lasso's loop, and ", " between
    set terms), so breaks land in meaningful places.
    """
    print(f"{label}:")
    for line in textwrap.wrap(value, width=width - indent,
                              break_long_words=False, break_on_hyphens=False,
                              initial_indent=" " * indent,
                              subsequent_indent=" " * indent) or [" " * indent]:
        print(line)
    if trailing_blank:
        print()


def print_cli_results(result_data, pi_override=None, show_pi=True, show_tau=False,
                      pi_label=None):
    """
    Takes the raw dictionary generated by the backend and formats it into
    human-readable terminal tables, coloring the pinned inputs green.

    `show_pi=False` suppresses the PI line entirely.

    `show_tau=True` adds the Tau witness back: the `found reason representation
    Tau` block and the Tau column beside Pi in the table (see the module
    docstring for why it is off by default).

    `pi_label` overrides the label of that line (option 1 passes "PI" with the
    user's full [lasso] as `pi_override`, so the line is not called "found").

    `pi_override` prints that string instead of `result_data['pi_string']`.
    Callers that synthesized the trace themselves (pi_finder) use this: the PI
    the MSR pipeline reports back is projected onto the INPUTS and re-unrolled,
    whereas the trace they found is over the real system and carries its
    outputs, so it is the one worth showing.
    """
    print(f"Effect: {result_data['effect']}")
    status = result_data["status"]
    # Which solver produced this. The backends fill it in; the default keeps
    # the wording right for results built before the field existed.
    solver = result_data.get("solver", "AutoHyper")

    # --- ERROR & EDGE CASE HANDLING ---
    if status == "NON_DETERMINISTIC":
        print(f"\n{'='*80}")
        print(" \033[95m[!] STATUS: AMBIGUOUS SYSTEM (Non-Deterministic)\033[0m")
        print(f"{'='*80}")
        print(" Causality requires an input-deterministic system. Your system allows")
        print(" multiple different outcomes for the exact same input state.")
        print(f"\n DETAILS: {result_data.get('error_msg')}")
        print(f"{'='*80}\n")
        return

    if status == "ERROR":
        print(f"\n{'='*80}")
        print(" \033[91m[!] EXECUTION FAILED\033[0m")
        print(f"{'='*80}")
        print(result_data.get('error_msg', 'Unknown Error'))
        print(f"{'='*80}\n")
        return

    if status == "INVALID_PI":
        print(f"\n{'='*80}")
        print(" \033[91mSTATUS: INVALID TRACE (Pi is not a valid path or does not satisfy the effect!)\033[0m")
        print(f"{'='*80}")
        detail = result_data.get("invalid_detail")
        if detail:
            # From trace_check: exact, and before any solver ran.
            print(" The trace in the [lasso] block is not a path of the system's HOA graph:")
            for line in textwrap.wrap(detail, width=76, initial_indent="   ",
                                      subsequent_indent="   "):
                print(line)
            print(" No cause is computed for it: on a trace the system cannot produce, a")
            print(" reason can be \"sufficient\" only vacuously.")
        else:
            print(f" {solver} proved that the trace provided in the [lasso] block is either:")
            print("   - not a physically possible path within the system's HOA graph, or")
            print("   - a valid path on which the [effect] formula does not actually occur.")
        print(" -> Aborting causality check.")
        print(f"{'='*80}\n")
        return

    if status == "UNSAT_NO_CAUSE":
        print(f"\n{'='*80}")
        print(" \033[93mSTATUS: UNSAT (Valid Trace, but No Cause Exists)\033[0m")
        print(f"{'='*80}")
        print(f" The Pi trace is valid, but {solver} proved that no sufficient")
        print(" cause exists for this system configuration.")
        print(f"{'='*80}\n")
        return

    if status == "UNKNOWN_BOUNDED":
        # HyperQB only. A bounded `unsat` is "no witness within k", never "no
        # cause exists", so it gets its own status rather than being folded into
        # UNSAT_NO_CAUSE -- the two mean different things and only one is a
        # proof. See hyperqb_analyzer's module docstring.
        print(f"\n{'='*80}")
        print(f" \033[93mSTATUS: UNDECIDED AT THIS BOUND ({solver})\033[0m")
        print(f"{'='*80}")
        for line in textwrap.wrap(result_data.get("bounded_note", ""), width=78,
                                  initial_indent=" ", subsequent_indent=" "):
            print(line)
        print(" This is NOT a proof that no cause exists. Raise the bound"
              " (--k), or re-run")
        print(" without --hyperQB: the AutoHyper backend is exact.")
        print(f"{'='*80}\n")
        return

    # --- SUCCESS HANDLING ---
    if status == "SAT_MSR":
        print("\n\033[92mStatus: SAT (Minimal Sufficient Reason Found)\033[0m\n")
    elif status == "SAT_SR" and "k" in result_data:
        # A BOUNDED backend reached SR. That is a much weaker statement than
        # the exact one below: "no MSR witness inside k", not "no MSR exists".
        # Printing the exact explanation here would assert a proof the solver
        # never gave.
        print("\n\033[93mStatus: SAT (a Sufficient Reason; minimality UNDECIDED at this "
              "bound)\033[0m\n")
        print("\033[2m  Why: the MSR query found no witness within the bound, and the SR query\033[0m")
        print("\033[2m  did. Whether a MINIMAL sufficient reason exists is open -- a bounded\033[0m")
        print("\033[2m  UNSAT is not a proof. The reason below is genuinely sufficient; it may\033[0m")
        print("\033[2m  or may not be minimal. Re-run without --hyperQB for an exact answer.\033[0m\n")
    elif status == "SAT_SR":
        print("\n\033[93mStatus: SAT (No Minimal Cause found, but found a Sufficient Reason)\033[0m\n")
        # Not a solver failure: when no MSR exists, every sufficient reason is
        # infinite and each one strictly contains a smaller sufficient reason,
        # so there is no smallest one to report. Typical for liveness effects
        # (G F / F G), where a cause can be pushed further into the future
        # forever.
        print("\033[2m  Why: no MSR exists for this instance -- the sufficient reasons form an\033[0m")
        print("\033[2m  infinite descending chain R0 > R1 > R2 > ..., so none is minimal.\033[0m")
        print("\033[2m  The reason below is sufficient but not minimal.\033[0m\n")

    if "k" in result_data:
        # A bounded backend: say so on the result itself. `sat` under
        # pessimistic semantics means a witness was actually found, so this
        # reason is real -- the bound is reported for reproducibility, not as a
        # caveat on the answer.
        print(f"\033[2m  ({solver}, bounded: k={result_data['k']}, "
              f"{result_data.get('semantics', 'pes')} semantics -- a witness "
              f"found within the bound is a proof)\033[0m\n")

    note = result_data.get("bounded_note")
    if note:
        for line in textwrap.wrap("Note: " + note, width=88,
                                  initial_indent="\033[2m  ",
                                  subsequent_indent="  "):
            print(line)
        print(RESET)

    if show_pi:
        # "found" only when we synthesized the trace ourselves; in option 1 the
        # PI came from the user's [lasso] block. strip() because an empty lasso
        # prefix renders as a leading space.
        _label = pi_label or ("found PI" if pi_override else "PI")
        _print_block(_label, (pi_override or result_data["pi_string"]).strip(),
                     trailing_blank=True)
    if show_tau:
        _print_block("found reason representation Tau",
                     result_data["tau_string"].strip(), trailing_blank=True)
    _td = result_data.get("table_data") or {}
    # A bounded backend can only show the part of R that fits inside its bound;
    # the label has to say so, because a truncated R is not a reason.
    _r_label = ("Reason R" if result_data.get("reason_complete", True)
                else "Reason R (TRUNCATED — see the note above)")
    _print_block(_r_label,
                 format_reason_set(_td.get("tau_prefix", []),
                                   _td.get("tau_cycle", []),
                                   result_data["cause_vars"] or []))

    # --- DYNAMIC TABLE FORMATTING ---
    vars_to_show = result_data["cause_vars"]
    if not vars_to_show:
        vars_to_show = ["(No specific cause vars detected)"]

    _TAU_HDR, _PI_HDR = 'REASON REPRESENTATION (Tau)', 'ACTUAL TRACE (Pi)'
    col_width = max(len(_TAU_HDR if show_tau else _PI_HDR),
                    len('(Repeating Pattern)'),      # the cycle banner sits in this column too
                    len(vars_to_show) * 8)
    rule = '=' * (col_width * 2 + 25 if show_tau else col_width + 26)

    print(f"\n{rule}")
    if show_tau:
        print(f"{'TIME':<5} | {_TAU_HDR:<{col_width}} | {_PI_HDR:<{col_width}} | {'STATUS'}")
    else:
        print(f"{'TIME':<5} | {_PI_HDR:<{col_width}} | {'REASON (R)'}")
    print(rule)

    def fmt(v_set, green_vars):
        """
        Format a set of active variables into a 'name=T/F' string.
        Any variable in `green_vars` (the inputs pinned by Tau) is wrapped in
        green.  Returns (colored_string, visible_length) so callers can pad
        correctly despite the invisible ANSI escape codes.
        """
        parts = []
        visible_len = 0
        for i, v in enumerate(vars_to_show):
            if v == "(No specific cause vars detected)":
                return "", 0
            val = "T" if v in v_set else "F"
            token = f"{v}={val}"
            sep = "" if i == 0 else ", "
            visible_len += len(sep) + len(token)
            if v in green_vars:
                parts.append(f"{sep}{GREEN}{token}{RESET}")
            else:
                parts.append(f"{sep}{token}")
        return "".join(parts), visible_len

    def pad(cell, visible_len):
        """Pad a (possibly colored) cell to col_width using its visible length."""
        return cell + " " * max(0, col_width - visible_len)

    def print_row(t, tau_vars, pi_vars):
        """Print one timestep row with per-variable green highlighting."""
        # The inputs that are TRUE in Tau are exactly the ones R pins at t.
        green_list = [v for v in vars_to_show if v in tau_vars]
        green_vars = set(green_list)
        pi_cell, pi_len = fmt(pi_vars, green_vars)

        if show_tau:
            marker = f"{GREEN}<-- REASON DETECTED{RESET}" if green_vars else ""
            tau_cell, tau_len = fmt(tau_vars, green_vars)
            print(f"{t:<5} | {pad(tau_cell, tau_len)} | {pad(pi_cell, pi_len)} | {marker}")
            return
        # Compact: name the pinned variables, since there is no Tau column left
        # to read them off.
        marker = (f"{GREEN}<-- R pins " + ", ".join(green_list) + RESET
                  if green_list else "")
        print(f"{t:<5} | {pad(pi_cell, pi_len)} | {marker}".rstrip())

    # --- PREFIX PRINTING ---
    td = result_data["table_data"]
    pi_p, pi_c = td["pi_prefix"], td["pi_cycle"]
    tau_p, tau_c = td["tau_prefix"], td["tau_cycle"]

    max_prefix = max(len(pi_p), len(tau_p))
    for i in range(max_prefix):
        p_step = pi_p[i] if i < len(pi_p) else set()
        t_step = tau_p[i] if i < len(tau_p) else set()
        print_row(i, t_step, p_step)

    # --- CYCLE PRINTING ---
    # A backend can hand back a trace with no repeating part: the bounded
    # backend does exactly that when its witness is not periodic within the
    # bound. Printing an empty "(Repeating Pattern)" block there would assert a
    # loop that was never established.
    if not pi_c and not tau_c:
        print(f"{rule}\n")
        return

    if show_tau:
        sep = f"{'-'*5} + {'-'*col_width} + {'-'*col_width} + {'-'*15}"
        head = (f"{'CYCLE':<5} | {'(Repeating Pattern)':<{col_width}} | "
                f"{'(Repeating Pattern)':<{col_width}} |")
    else:
        sep = f"{'-'*5} + {'-'*col_width} + {'-'*15}"
        head = f"{'CYCLE':<5} | {'(Repeating Pattern)':<{col_width}} |"
    print(sep)
    print(head)
    print(sep)

    max_cycle = max(len(pi_c), len(tau_c))
    current_time_idx = max_prefix
    for i in range(max_cycle):
        p_step = pi_c[i] if i < len(pi_c) else set()
        t_step = tau_c[i] if i < len(tau_c) else set()
        print_row(current_time_idx, t_step, p_step)
        current_time_idx += 1

    print(f"{rule}\n")


def main():
    import proc_guard
    proc_guard.install_termination_handlers()
    if len(sys.argv) < 2:
        print("Usage: python3 cli_viewer.py <input.txt> [--with-tau]")
        sys.exit(1)
    results = trace_analyzer.analyze_trace(sys.argv[1])
    print_cli_results(results, show_tau="--with-tau" in sys.argv[2:])


if __name__ == "__main__":
    main()
